String _csvField(String v) =>
    v.contains(',') || v.contains('"') || v.contains('\n') ? '"${v.replaceAll('"', '""')}"' : v;

/// `data/items.csv` (RFC 4180, CRLF line endings). [hardcore] gives the
/// hardcore-balance variant: weaker weapons, higher prices.
String itemsCsv({bool hardcore = false}) {
  final rows = <List<String>>[
    ['id', 'name', 'type', 'damage', 'price', 'rarity'],
    for (final i in _items)
      [
        i.id,
        i.name,
        i.type,
        '${hardcore ? i.damage * 4 ~/ 5 : i.damage}',
        '${hardcore ? i.price * 3 ~/ 2 : i.price}',
        i.rarity,
      ],
  ];
  return rows.map((r) => r.map(_csvField).join(',')).map((l) => '$l\r\n').join();
}

