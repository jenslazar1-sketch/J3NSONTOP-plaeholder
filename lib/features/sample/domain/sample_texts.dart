String balanceToml(BalancePreset p) {
  final b = StringBuffer()
    ..writeln('# Neon Dungeon - balance values')
    ..writeln('# ${p.comment}')
    ..writeln()
    ..writeln('title = "${p.title}"')
    ..writeln('game_version = "$sampleGameVersion"')
    ..writeln('last_tuned = 2026-09-01T12:00:00Z')
    ..writeln('season_start = 2026-09-01')
    ..writeln('difficulty_scale = ${p.scale}')
    ..writeln('permadeath = ${p.permadeath}')
    ..writeln()
    ..writeln('[player]')
    ..writeln('max_health = ${p.maxHealth}')
    ..writeln('max_mana = ${p.maxMana}')
    ..writeln('move_speed = 4.5')
    ..writeln('crit_chance = ${p.critChance}')
    ..writeln('crit_multiplier = 1.5')
    ..writeln('starting_items = [${p.startingItems.map((s) => '"$s"').join(', ')}]')
    ..writeln('regen = { health_per_second = ${p.healthRegen}, mana_per_second = 1.0 }')
    ..writeln()
    ..writeln('[economy]')
    ..writeln('starting_gold = ${p.startingGold}')
    ..writeln('max_gold = 999_999')
    ..writeln('sell_ratio = ${p.sellRatio}')
    ..writeln('shop_restock_minutes = 10')
    ..writeln('price_multiplier = ${p.priceMultiplier}')
    ..writeln()
    ..writeln('[economy.drop_rates]')
    ..writeln('common = ${p.drops[0]}')
    ..writeln('uncommon = ${p.drops[1]}')
    ..writeln('rare = ${p.drops[2]}')
    ..writeln('legendary = ${p.drops[3]}');
  for (final e in _balanceEnemies) {
    b
      ..writeln()
      ..writeln('[[enemies]]')
      ..writeln('id = "${e.id}"')
      ..writeln('health = ${e.health * p.enemyHealth ~/ 100}')
      ..writeln('damage = ${e.damage * p.enemyDamage ~/ 100}')
      ..writeln('xp = ${e.xp}')
      ..writeln('spawn_weight = ${e.weight}');
    if (e.boss) b.writeln('boss = true');
  }
  return b.toString();
}

