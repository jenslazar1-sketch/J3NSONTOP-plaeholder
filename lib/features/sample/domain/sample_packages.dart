/// One sample profile (see docs/MOD_FORMAT.md).
class SampleProfile {
  const SampleProfile(this.id, this.name, this.description, this.mods);
  final String id;
  final String name;
  final String description;
  final List<String> mods;

  String get fileName => '$id.j3profile.json';

  Map<String, Object?> toJson() => {
    'format': 'j3profile',
    'formatVersion': 1,
    'id': id,
    'name': name,
    'description': description,
    'target': 'game',
    'mods': [
      for (final m in mods) {'id': m, 'enabled': true},
    ],
  };
}

