/// Fixed timestamp stored in every sample archive entry.
final DateTime sampleArchiveTime = DateTime(2026, 9, 1, 12);

const Map<String, String> _gameCompat = {'game': sampleGameId, 'gameVersion': '>=1.4.0 <2.0.0'};

/// One sample mod package (see docs/MOD_FORMAT.md).
class SamplePackage {
  SamplePackage({
    required this.id,
    required this.name,
    required this.version,
    required this.description,
    required this.payload,
    required this.readmeNotes,
    this.compatibility = _gameCompat,
    this.dependencies = const [],
    this.conflicts = const [],
    this.tags = const [],
    this.preview,
  });

  final String id;
  final String name;
  final String version;
  final String description;

  /// Target path (relative to the profile target folder) -> content.
  final Map<String, List<int>> payload;
  final String readmeNotes;
  final Map<String, String> compatibility;
  final List<Map<String, String>> dependencies;
  final List<Map<String, String>> conflicts;
  final List<String> tags;
  final Uint8List? preview;

  String get fileName => '$id-$version.j3mod';

  Map<String, Object?> manifest() => {
    'format': 'j3mod',
    'formatVersion': 1,
    'id': id,
    'name': name,
    'version': version,
    'description': description,
    'author': 'J3NSONTOP samples',
    'license': 'CC0-1.0',
    'compatibility': compatibility,
    'files': [
      for (final target in payload.keys) {'source': 'files/$target', 'target': target},
    ],
    if (dependencies.isNotEmpty) 'dependencies': dependencies,
    if (conflicts.isNotEmpty) 'conflicts': conflicts,
    if (tags.isNotEmpty) 'tags': tags,
  };

  String readme() {
    final b = StringBuffer()
      ..writeln('# $name $version')
      ..writeln()
      ..writeln(description)
      ..writeln()
      ..writeln(
        'Sample package for the fictional game *$sampleGameName* '
        '(`${compatibility['game']}` ${compatibility['gameVersion'] ?? 'any version'}), '
        'generated by J3NSONTOP. License: CC0-1.0.',
      )
      ..writeln()
      ..writeln('## Files')
      ..writeln()
      ..writeln('| Package source | Target (inside the profile target folder) |')
      ..writeln('| --- | --- |');
    for (final target in payload.keys) {
      b.writeln('| `files/$target` | `$target` |');
    }
    b
      ..writeln()
      ..writeln('## Dependencies')
      ..writeln();
    if (dependencies.isEmpty) {
      b.writeln('None.');
    } else {
      for (final d in dependencies) {
        b.writeln('- `${d['id']}` ${d['version'] ?? 'any'}');
      }
    }
    b
      ..writeln()
      ..writeln('## Notes')
      ..writeln()
      ..writeln(readmeNotes);
    return b.toString();
  }

  /// Deterministic ZIP bytes: Stored entries, fixed timestamps, fixed order.
  /// Stored (not Deflate) keeps the bytes identical on every platform, since
  /// the platform zlib may compress differently.
  Uint8List zip() {
    final archive = Archive();
    void add(String name, List<int> bytes) {
      archive.add(ArchiveFile.bytes(name, bytes)..compression = CompressionType.none);
    }

    add('j3mod.json', utf8.encode(prettyJsonText(manifest())));
    add('README.md', utf8.encode(readme()));
    if (preview != null) add('preview.png', preview!);
    payload.forEach((target, bytes) => add('files/$target', bytes));
    return ZipEncoder().encodeBytes(archive, modified: sampleArchiveTime);
  }
}

